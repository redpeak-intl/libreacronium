;
; boot64.asm — загрузочный код ядра для x86_64 (amd64).
;
; GRUB передаёт управление в 32-битном protected mode (это требование
; спецификации Multiboot). Данный bootstrap:
;   1) принимает управление в 32 битах;
;   2) строит простейшие таблицы страниц (идентичное отображение первых 1 GiB);
;   3) включает PAE, long mode (EFER.LME) и страничную адресацию (CR0.PG);
;   4) загружает 64-битную GDT и выполняет far jump в 64-битный сегмент кода;
;   5) уже в long mode настраивает сегменты/стек и вызывает kmain(magic, mbi).
;

; ----------------------------------------------------------------------
;  32-битная часть: заголовок Multiboot и подготовка long mode
; ----------------------------------------------------------------------
[BITS 32]

section .text
        align 4
        dd 0x1BADB002              ; Магическое число Multiboot
        dd 0x02                    ; Флаги: запросить информацию о памяти (mem_*)
        dd - (0x1BADB002 + 0x02)   ; Контрольная сумма

global start
extern kmain

start:
        cli                        ; Прерывания пока запрещены

        ; Сохраняем аргументы Multiboot: eax — магия, ebx — адрес MBI.
        ; Кладём их в edi/esi (первый и второй аргументы System V ABI).
        mov edi, eax
        mov esi, ebx

        ; --- Связывание таблиц страниц задано статически (см. .data) ---
        ; PML4[0] -> PDPT, PDPT[0..3] -> PD/PD1/PD2/PD3 (идентично 4 GiB).

        ; --- CR3 = физический адрес PML4 ---
        mov eax, pml4
        mov cr3, eax

        ; --- Включаем PAE (CR4.PAE, бит 5) ---
        mov eax, cr4
        or  eax, (1 << 5)
        mov cr4, eax

        ; --- Включаем long mode (EFER.LME, бит 8) ---
        mov ecx, 0xC0000080        ; IA32_EFER
        rdmsr
        or  eax, (1 << 8)
        wrmsr

        ; --- Включаем страничную адресацию (CR0.PG, бит 31) ---
        mov eax, cr0
        or  eax, (1 << 31)
        mov cr0, eax

        ; --- Загружаем 64-битную GDT и прыгаем в 64-битный сегмент кода ---
        lgdt [gdt64_ptr]
        jmp 0x08:long_mode_start

; ----------------------------------------------------------------------
;  64-битная часть: настройка сегментов/стека и вызов kmain
; ----------------------------------------------------------------------
[BITS 64]

long_mode_start:
        mov ax, 0x10               ; селектор сегмента данных
        mov ds, ax
        mov es, ax
        mov ss, ax
        mov fs, ax
        mov gs, ax

        mov rsp, stack_top         ; стек растёт вниз от вершины
        cld

        ; Аргументы уже в edi (magic) и esi (mbi_addr).
        call kmain

        hlt                        ; на всякий случай

; ----------------------------------------------------------------------
;  64-битная GDT
; ----------------------------------------------------------------------
section .rodata
align 8
gdt64:
        dq 0x0000000000000000      ; null-дескриптор
gdt64_code:
        dq 0x00209A0000000000      ; 64-битный код: P=1, DPL=0, S=1, type=A, L=1
gdt64_data:
        dq 0x0000920000000000      ; данные: P=1, DPL=0, S=1, type=2
gdt64_ptr:
        dw gdt64_ptr - gdt64 - 1   ; предел (размер GDT - 1)
        dq gdt64                   ; линейный (== физический) адрес GDT

; ----------------------------------------------------------------------
;  Таблицы страниц: идентичное отображение первых 4 GiB.
;
;  PML4[0] -> PDPT; PDPT[0..3] -> PD/PD1/PD2/PD3, каждая PD описывает 1 GiB
;  через 512 страниц по 2 MiB. Отображение первых 4 GiB (а не только 1 GiB)
;  нужно, чтобы MMIO-области PCI-устройств (например, e1000 у ~0xFEBE0000)
;  были доступны напрямую сразу после включения long mode.
; ----------------------------------------------------------------------
section .data
align 4096
pml4:
        dq pdpt + 0x0003            ; [0] -> pdpt (present|rw)
        times 511 dq 0

align 4096
pdpt:
        dq pd  + 0x0003             ; [0] -> 0x00000000 - 0x3FFFFFFF
        dq pd1 + 0x0003             ; [1] -> 0x40000000 - 0x7FFFFFFF
        dq pd2 + 0x0003             ; [2] -> 0x80000000 - 0xBFFFFFFF
        dq pd3 + 0x0003             ; [3] -> 0xC0000000 - 0xFFFFFFFF
        times 508 dq 0

; PD (0 GiB)
align 4096
pd:
%assign i 0
%rep 512
        dq (i << 21) | 0x83
%assign i i+1
%endrep
; PD1 (1 GiB)
align 4096
pd1:
%assign i 0
%rep 512
        dq ((512 + i) << 21) | 0x83
%assign i i+1
%endrep
; PD2 (2 GiB)
align 4096
pd2:
%assign i 0
%rep 512
        dq ((1024 + i) << 21) | 0x83
%assign i i+1
%endrep
; PD3 (3 GiB)
align 4096
pd3:
%assign i 0
%rep 512
        dq ((1536 + i) << 21) | 0x83
%assign i i+1
%endrep

; ----------------------------------------------------------------------
;  Стек ядра (16 KiB)
; ----------------------------------------------------------------------
section .bss
align 16
stack_bottom:
        resb 16384
stack_top:
