/**
 * @file e1000.h
 * @brief Драйвер сетевой карты Intel e1000 (82540EM и совместимые).
 *
 * Драйвер опрашивает приёмный кольцевой буфер (polling) и умеет передавать
 * кадры. Используется сетевым стеком lwip через слой ethernetif.
 */

#ifndef E1000_H
#define E1000_H

#include <stdint.h>

/**
 * @brief Найти и инициализировать карту e1000.
 * @return 0 при успехе, отрицательное значение при ошибке.
 */
int e1000_init(void);

/** @brief Скопировать MAC-адрес карты в буфер из 6 байт. */
void e1000_get_mac(uint8_t mac[6]);

/**
 * @brief Передать один кадр.
 * @param data Указатель на данные кадра (без CRC).
 * @param len  Длина кадра в байтах.
 * @return 0 при успехе, отрицательное значение при ошибке.
 */
int e1000_transmit(const void *data, uint32_t len);

/**
 * @brief Забрать один принятый кадр (если готов).
 * @param buffer Буфер назначения.
 * @param len    На входе — размер буфера, на выходе — длина кадра.
 * @return 1 если кадр получен, 0 если кадров нет.
 */
int e1000_receive(void *buffer, uint32_t *len);

/** @brief 1, если линк поднят (по статусу карты). */
int e1000_link_up(void);

/** @brief Инициализирована ли карта. */
int e1000_present(void);

#endif /* E1000_H */
